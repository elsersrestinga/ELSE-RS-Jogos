class Defesa:
    def __init__(self, x, y):
        self.grupo_blocos = pygame.sprite.Group()
        for linha in range(len(grid)):
            for coluna in range(len(grid[0])):
                if grid[linha][coluna] == 1:
                    pos_x = x + coluna * 3
                    pos_y = y + linha * 3
                    bloco = Bloco(pos_x, pos_y)
                    self.grupo_blocos.add(bloco)